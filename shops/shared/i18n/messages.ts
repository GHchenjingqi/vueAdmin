const messages: Record<Locale, Record<string, string>> = { 'en-US': en, 'zh-CN': zh }

export function translate(locale: Locale, key: string): string {
  return messages[locale]?.[key] ?? messages[defaultLocale][key] ?? key
}

/** 带插值：translateI('newsletter.success', 'zh-CN', { email: 'a@b.c' }) */
export function translateI(locale: Locale, key: string, vars: Record<string, string>): string {
  let s = translate(locale, key)
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v)
  return s
}
